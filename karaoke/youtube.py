SETUP_HELP = (
    "No YouTube sign-in is set up. In Google Cloud: create a project, enable 'YouTube Data API v3', "
    "configure the OAuth consent screen (External, add your account as a test user), create an OAuth "
    "client of type 'Desktop app' and save its JSON as {path}. See docs/youtube.md."
)


def service() -> Any:
    """An authorised YouTube API client. The first call opens a browser to sign in."""
    from google.auth.transport.requests import Request
    from google.oauth2.credentials import Credentials
    from google_auth_oauthlib.flow import InstalledAppFlow
    from googleapiclient.discovery import build

    s = get_settings()
    creds = None
    if s.youtube_token.exists():
        creds = Credentials.from_authorized_user_file(str(s.youtube_token), SCOPES)
    if creds and creds.expired and creds.refresh_token:
        try:
            creds.refresh(Request())
        except Exception:  # noqa: BLE001 — a revoked or expired refresh token: sign in again
            creds = None
    if not creds or not creds.valid:
        if not s.youtube_client_secret.exists():
            raise ValueError(SETUP_HELP.format(path=s.youtube_client_secret))
        flow = InstalledAppFlow.from_client_secrets_file(str(s.youtube_client_secret), SCOPES)
        creds = flow.run_local_server(port=0, prompt="consent")
        s.youtube_token.parent.mkdir(parents=True, exist_ok=True)
        s.youtube_token.write_text(creds.to_json(), encoding="utf-8")
        s.youtube_token.chmod(0o600)
    return build("youtube", "v3", credentials=creds, cache_discovery=False)


def _body(y: YouTubeUpload, video_id: str | None = None) -> dict:
    snippet: dict[str, Any] = {"title": y.title, "description": y.description, "tags": y.tags,
                               "categoryId": y.category_id}
    if y.language:
        snippet["defaultLanguage"] = y.language
    if y.audio_language:
        snippet["defaultAudioLanguage"] = y.audio_language
    body: dict[str, Any] = {
        "snippet": snippet,
        "status": {"privacyStatus": y.privacy, "selfDeclaredMadeForKids": y.made_for_kids,
                   "containsSyntheticMedia": y.contains_synthetic_media},
    }
    if video_id:
        body["id"] = video_id
    return body


UPLOAD_LIMIT_HELP = (
    "YouTube refused the upload: this channel reached its daily upload limit (about 10 videos a day "
    "for a channel without phone verification; https://www.youtube.com/verify raises it). Try again tomorrow."
)
RETRY_STATUS = (500, 502, 503, 504)
MAX_RETRIES = 8


def _retryable(exc: Exception) -> bool:
    status = getattr(getattr(exc, "resp", None), "status", None)
    return isinstance(exc, (OSError, TimeoutError)) or (status is not None and int(status) in RETRY_STATUS)


def _resumable(request: Any, log: Callable[[str], None], sleep: Callable[[float], None] = time.sleep) -> dict:
    response = None
    tries = 0
    last = -1
    while response is None:
        try:
            status, response = request.next_chunk()
            tries = 0
            if status is not None:
                pct = int(status.progress() * 100)
                if pct // 10 != last // 10:
                    log(f"uploading… {pct}%")
                last = pct
        except Exception as exc:  # noqa: BLE001 — retried when YouTube or the network hiccups
            if not _retryable(exc) or tries >= MAX_RETRIES:
                raise
            tries += 1
            wait = min(2 ** tries, 60)
            log(f"upload interrupted ({exc}); retrying in {wait}s")
            sleep(wait)
    return response


def _playlist_id(yt: Any, title: str, log: Callable[[str], None]) -> str:
    req = yt.playlists().list(part="snippet", mine=True, maxResults=50)
    while req is not None:
        res = req.execute()
        for it in res.get("items", []):
            if it["snippet"]["title"] == title:
                return it["id"]
        req = yt.playlists().list_next(req, res)
    res = yt.playlists().insert(part="snippet,status", body={
        "snippet": {"title": title}, "status": {"privacyStatus": "private"}}).execute()
    log(f"created the private playlist {title!r}")
    return res["id"]


def upload(p: JobPaths, yt: Any = None, *, privacy: str | None = None, again: bool = False,
           log: Callable[[str], None] = print, sleep: Callable[[float], None] = time.sleep) -> YouTubeUpload:
    """Upload output/karaoke.mp4 with output/youtube.json. Saves the video id as soon as YouTube
    gives it, so a failure afterwards (thumbnail, playlist) never leads to a second copy."""
    from googleapiclient.http import MediaFileUpload

    y = read_model_opt(p.youtube, YouTubeUpload)
    if y is None:
        raise ValueError("no output/youtube.json: run `karaoke publish <job>` first and read it")
    if y.video_id and not again:
        raise ValueError(f"already uploaded: https://youtu.be/{y.video_id}. Use --update to send edits of "
                         "youtube.json to it, or --again to upload another copy")
    if privacy:
        y = y.model_copy(update={"privacy": privacy})
    errors = check(y)
    if errors:
        raise ValueError("youtube.json: " + "; ".join(errors))
    if not p.final_video.exists():
        raise ValueError(f"no {p.rel(p.final_video)}")
    yt = yt or service()
    media = MediaFileUpload(str(p.final_video), mimetype="video/mp4", chunksize=8 * 1024 * 1024, resumable=True)
    request = yt.videos().insert(part="snippet,status", body=_body(y), media_body=media)
    try:
        response = _resumable(request, log, sleep)
    except Exception as exc:
        if "uploadLimitExceeded" in str(exc):
            raise ValueError(UPLOAD_LIMIT_HELP) from exc
        raise
    vid = response["id"]
    y = y.model_copy(update={"video_id": vid, "uploaded_at": now(), "video_sha1": file_hash(p.final_video)})
    write_model(p.youtube, y)
    log(f"uploaded ({y.privacy}): https://youtu.be/{vid}")
    up = response.get("status", {})
    if up.get("uploadStatus") in ("rejected", "failed"):
        log(f"YouTube says the upload {up['uploadStatus']}: {up.get('rejectionReason') or up.get('failureReason')}")
    _extras(p, yt, y, log)
    return y


def _extras(p: JobPaths, yt: Any, y: YouTubeUpload, log: Callable[[str], None]) -> None:
    from googleapiclient.http import MediaFileUpload

    if y.tags:  # the first real upload came back with no tags; a second write kept them
        try:
            items = yt.videos().list(part="snippet", id=y.video_id).execute().get("items", [])
            if items and not items[0]["snippet"].get("tags"):
                yt.videos().update(part="snippet,status", body=_body(y, y.video_id)).execute()
                log("tags sent again (YouTube had not kept them)")
        except Exception as exc:  # noqa: BLE001 — the video is up; `--update` sends them later
            log(f"could not check the tags ({exc}); run --update to send them again")
    if y.thumbnail and (p.root / y.thumbnail).exists():
        try:
            yt.thumbnails().set(videoId=y.video_id, media_body=MediaFileUpload(
                str(p.root / y.thumbnail), mimetype="image/jpeg")).execute()
            log("thumbnail set")
        except Exception as exc:  # noqa: BLE001 — custom thumbnails need a phone-verified channel
            if getattr(getattr(exc, "resp", None), "status", None) == 403:
                log("thumbnail not set: custom thumbnails need a phone-verified channel (youtube.com/verify)")
            else:
                log(f"thumbnail not set ({exc})")
    if y.playlist:
        try:
            pid = _playlist_id(yt, y.playlist, log)
            yt.playlistItems().insert(part="snippet", body={"snippet": {
                "playlistId": pid, "resourceId": {"kind": "youtube#video", "videoId": y.video_id}}}).execute()
            log(f"added to the playlist {y.playlist!r}")
        except Exception as exc:  # noqa: BLE001 — the video is up; the playlist can be fixed in Studio
            log(f"not added to the playlist ({exc})")


def update(p: JobPaths, yt: Any = None, *, privacy: str | None = None,
           log: Callable[[str], None] = print) -> YouTubeUpload:
    """Send the title, description, tags and privacy in youtube.json to the video already uploaded."""
    y = read_model_opt(p.youtube, YouTubeUpload)
    if not y or not y.video_id:
        raise ValueError("this job has not been uploaded yet")
    if privacy:
        y = y.model_copy(update={"privacy": privacy})
    errors = check(y)
    if errors:
        raise ValueError("youtube.json: " + "; ".join(errors))
    yt = yt or service()
    yt.videos().update(part="snippet,status", body=_body(y, y.video_id)).execute()
    write_model(p.youtube, y)
    log(f"updated ({y.privacy}): https://youtu.be/{y.video_id}")
    if y.video_sha1 and p.final_video.exists() and file_hash(p.final_video) != y.video_sha1:
        log("note: output/karaoke.mp4 changed since the upload; YouTube cannot replace a video's file. "
            "Upload it again with --again (and delete the old one in Studio) to show the new render")
    return y
