# --------------------------------------------------------------------------- licences


def licence_url(name: str | None) -> str | None:
    """The page of a licence named like the picture sources name them ('CC BY-SA 3.0', 'CC0')."""
    if not name:
        return None
    n = name.strip()
    m = re.match(r"^CC[ -]?(BY(?:-NC)?(?:-SA|-ND)?)[ -]?(\d\.\d)", n, re.I)
    if m:
        return f"https://creativecommons.org/licenses/{m.group(1).lower()}/{m.group(2)}/"
    if re.match(r"^CC[ -]?0|^CC[ -]?Zero", n, re.I):
        return "https://creativecommons.org/publicdomain/zero/1.0/"
    if "unsplash" in n.lower():
        return "https://unsplash.com/license"
    if "pexels" in n.lower():
        return "https://www.pexels.com/license/"
    return None


def _licence_problem(name: str | None) -> str | None:
    if not name:
        return "has no licence recorded"
    up = name.upper()
    if "-ND" in up:
        return f"is {name}: no changes allowed, but the video crops, blurs and darkens it"
    if "-NC" in up:
        return f"is {name}: non-commercial only, and a Content ID claim may put ads on the video"
    if not licence_url(name) and "public domain" not in name.lower():
        return f"has a licence I do not know ({name}): check what it asks for"
    return None


# --------------------------------------------------------------------------- names


def _nice(s: str) -> str:
    """'SEQUÊNCIA STRIPTEASE' -> 'Sequência Striptease'; mixed case is kept as written."""
    s = s.strip()
    if s.isupper() and len(s) > 3:
        words = s.lower().split()
        s = " ".join(w if (i and w in _SMALL) else w[:1].upper() + w[1:] for i, w in enumerate(words))
    return re.sub(r"\bMc\b", "MC", s)  # funk artists: "Mc Gw" -> "MC Gw"


def _names(meta: Meta) -> tuple[str, str, list[str], list[str]]:
    """(artist, song, featured artists, other extras such as a version name)."""
    artist = _nice(meta.clean_artist or meta.artist or meta.uploader or "")
    song = _nice(meta.clean_title or meta.track or meta.title)
    feat: list[str] = []
    other: list[str] = []
    for e in meta.clean_extra:
        m = _FEAT.match(e)
        if m:
            feat += [_nice(x) for x in re.split(r"\s*(?:,|&| e | and )\s*", e[m.end():]) if x.strip()]
        elif e.strip():
            other.append(_nice(e))
    return artist, song, feat, other


def _language(p: JobPaths) -> str:
    job = read_model_opt(p.job, Job)
    if job and job.settings.language:
        return job.settings.language
    lf = read_model_opt(p.lyrics_final, LyricsFinal)
    lang = (lf.language or "")[:2] if lf else ""
    return lang if lang in _TEXT else "pt"


def _clean(s: str) -> str:
    return s.replace("<", "‹").replace(">", "›")  # YouTube refuses angle brackets in titles and descriptions


def make_title(artist: str, song: str, feat: list[str], other: list[str], lang: str) -> str:
    t = _TEXT[lang]
    extras = "".join(f" ({o})" for o in other) + (t["feat"].format(names=", ".join(feat)) if feat else "")
    for cand in (f"{artist} - {song}{extras} | {t['karaoke']} {t['suffix']}",
                 f"{artist} - {song}{extras} | {t['karaoke']}",
                 f"{artist} - {song} | {t['karaoke']} {t['suffix']}",
                 f"{artist} - {song} | {t['karaoke']}"):
        if len(cand) <= TITLE_MAX:
            return _clean(cand)
    return _clean(f"{song} | {t['karaoke']}")[:TITLE_MAX]


# --------------------------------------------------------------------------- chapters


def _stamp(t: float) -> str:
    t = int(round(t))
    h, m, s = t // 3600, t // 60 % 60, t % 60
    return f"{h}:{m:02d}:{s:02d}" if h else f"{m}:{s:02d}"


def chapters(st: Structure | None, lang: str, offset: float = 0.0) -> list[tuple[float, str]]:
    """Chapters from the song's sections: neighbours with the same label merged, sections shorter
    than YouTube's minimum folded into the one before. Empty if YouTube would not show them.
    ``offset``: the silence the video opens with (``render.ass.lead_pad_s``); the first chapter
    still starts at 0:00 and covers it."""
    if not st or not st.sections:
        return []
    merged: list[list[Any]] = []  # [start, end, label]
    for s in st.sections:
        if merged and (merged[-1][2] == s.label or s.end - s.start < CHAPTER_MIN_S):
            merged[-1][1] = s.end
        else:
            merged.append([s.start, s.end, s.label])
    if len(merged) > 1 and merged[0][1] - merged[0][0] < CHAPTER_MIN_S:  # a short first one joins the next
        merged[1][0] = merged[0][0]
        merged.pop(0)
    merged[0][0] = 0.0
    if len(merged) < CHAPTER_MIN_COUNT or any(e - s < CHAPTER_MIN_S for s, e, _ in merged):
        return []
    labels = _TEXT[lang]["labels"]
    count = {lab: sum(1 for *_, x in merged if x == lab) for _, _, lab in merged}
    seen: dict[str, int] = {}
    out = []
    for s, _, lab in merged:
        seen[lab] = seen.get(lab, 0) + 1
        name = labels[lab] + (f" {seen[lab]}" if count[lab] > 1 and lab in ("verse", "chorus") else "")
        out.append((s + offset if s > 0 else 0.0, name))
    return out


# --------------------------------------------------------------------------- picture credits


def picture_credits(p: JobPaths, lang: str) -> tuple[list[str], list[str]]:
    """(description lines, warnings) for the pictures the background actually shows."""
    bg = read_model_opt(p.background, Background)
    if not bg:
        return [], ["no background.json: the description says nothing about the background"]
    credits = json.loads(p.bg_credits.read_text(encoding="utf-8")) if p.bg_credits.exists() else {}
    t = _TEXT[lang]
    lines: list[str] = []
    warnings: list[str] = []
    seen: dict[str, set[str]] = {}
    order: list[tuple[str, Any]] = []
    kinds: set[str] = set()
    for sc in bg.scenes:
        src = sc.source
        if src.type == "generated" or src.type in ("color", "gradient"):
            kinds.add("generated")
            continue
        if src.type == "video":
            kinds.add("video")
            continue
        if src.type != "image" or not src.path:
            continue
        origin = (src.origin or "").lower()
        if origin == "thumbnail":
            kinds.add("cover")
            continue
        if origin == "video-frame":
            kinds.add("frames")
            continue
        if src.path not in seen:
            order.append((src.path, src))
        what = seen.setdefault(src.path, {"crop"})  # the frame is always cropped to 16:9
        if sc.blur > 0:
            what.add("blur")
        if sc.dim > 0:
            what.add("dim")
        if sc.motion != "none":
            what.add("motion")
    share_alike = False
    for path, src in order:
        c = credits.get(Path(path).name, {})
        lic = c.get("license") or src.license
        credit = c.get("credit") or src.credit
        page = c.get("page") or src.url or c.get("url")
        provider = (c.get("provider") or src.origin or "").lower()
        problem = _licence_problem(lic)
        if problem:
            warnings.append(f"{Path(path).name} {problem}")
        if not credit:
            warnings.append(f"{Path(path).name} has no credit recorded: add the author by hand")
            credit = Path(path).name
        what = ", ".join(t["what"][k] for k in ("crop", "blur", "dim", "motion") if k in seen[path])
        title = c.get("title")
        if provider in ("unsplash", "pexels"):
            line = f"• {credit}"
        else:
            author = credit
            if title and credit.endswith(", " + title):
                author = credit[: -len(title) - 2]
            line = f'• "{title}" – {author}' if title else f"• {credit}"
        if lic:
            url = licence_url(lic)
            line += f", {lic}" + (f" ({url})" if url else "")
        if provider == "wikimedia":
            line += ", via Wikimedia Commons"
        if page:
            line += f": {page}"
        line += f" ({t['changed'].format(what=what)})"
        lines.append(line)
        share_alike |= bool(lic and "-SA" in lic.upper())
    out: list[str] = []
    if lines:
        out += [t["pictures"], *lines]
        if share_alike:
            out.append(t["share_alike"])
    for k in ("cover", "frames", "video"):
        if k in kinds:
            out.append(t[k])
    if not out and "generated" in kinds:
        out.append(t["generated"])
    return out, warnings


# --------------------------------------------------------------------------- tags


def tags_length(tags: list[str]) -> int:
    """How YouTube counts the 500: each tag, plus 2 for the quotes around a tag with a space, plus
    the commas between tags."""
    return sum(len(t) + (2 if " " in t else 0) for t in tags) + max(len(tags) - 1, 0)


def make_tags(artist: str, song: str, feat: list[str], other: list[str], lang: str) -> list[str]:
    raw = [x.format(artist=artist, song=song) for x in _TAGS[lang]] + feat + other
    out: list[str] = []
    for tag in raw:
        tag = re.sub(r"[<>,]", "", tag).strip().lower()
        if tag and tag not in out and tags_length([*out, tag]) <= TAGS_MAX:
            out.append(tag)
    return out


def _hashtag(s: str) -> str:
    return "#" + re.sub(r"[^\w]", "", s.lower())


# --------------------------------------------------------------------------- thumbnail


def _title_card_time(p: JobPaths) -> float | None:
    """The middle of the title card in the rendered subtitles, if the video has one."""
    if not p.ass.exists():
        return None
    for line in p.ass.read_text(encoding="utf-8").splitlines():
        if line.startswith("Dialogue:") and ",Title," in line:
            a, b = line.split(",")[1:3]
            return (_secs(a) + _secs(b)) / 2
    return None


def _secs(stamp: str) -> float:
    h, m, s = stamp.strip().split(":")
    return int(h) * 3600 + int(m) * 60 + float(s)


def make_thumbnail(p: JobPaths, st: Structure | None) -> Path | None:
    """A 1280×720 frame of the finished video: the title card, else a few seconds into the first chorus."""
    if not p.final_video.exists():
        return None
    at = _title_card_time(p)
    if at is None:
        chorus = next((s for s in (st.sections if st else []) if s.label == "chorus"), None)
        at = chorus.start + 3.0 if chorus else 10.0
    cmd = [get_settings().ffmpeg_bin, "-y", "-loglevel", "error", "-ss", f"{at:.2f}", "-i", str(p.final_video),
           "-frames:v", "1", "-vf", "scale=1280:720", "-q:v", "3", str(p.thumbnail)]
    try:
        subprocess.run(cmd, check=True, capture_output=True)
    except (OSError, subprocess.CalledProcessError):
        return None
    return p.thumbnail if p.thumbnail.exists() else None


# --------------------------------------------------------------------------- draft


def build_draft(p: JobPaths) -> YouTubeUpload:
    meta = read_model(p.meta, Meta)
    st = read_model_opt(p.structure, Structure)
    lang = _language(p)
    t = _TEXT[lang]
    artist, song, feat, other = _names(meta)
    warnings: list[str] = []

    desc = [t["intro"].format(song=song, artist=artist,
                              feat=t["feat"].format(names=", ".join(feat)) if feat else "")]
    if meta.url:
        desc.append(t["original"].format(url=meta.url))
    job = read_model_opt(p.job, Job)
    lf = read_model_opt(p.lyrics_final, LyricsFinal)
    lead = lead_pad_s(lf, job.settings.render) if (lf and job) else 0.0
    chs = chapters(st, lang, lead)
    if chs:
        desc += ["", t["chapters"], *[f"{_stamp(s)} {name}" for s, name in chs]]
        warnings.append("the chapter names come from guessed section labels: check them against the song")
    desc += ["", t["rights"].format(artist=artist + (", " + ", ".join(feat) if feat else "")), t["made"]]
    pics, w = picture_credits(p, lang)
    warnings += w
    if pics:
        desc += ["", *pics]
    karaoke_tag = "#karaokê" if lang == "pt" else "#karaoke"
    desc += ["", " ".join(dict.fromkeys([karaoke_tag, _hashtag(artist), _hashtag(song)]))]
    if lang == "ja":
        warnings.append("Japanese song: add the title in Japanese script (and the anime, if any) to the title and tags")
    warnings.append("the backing track is the original recording: expect a Content ID claim. Check the "
                    "Copyright column in YouTube Studio before making it public")

    thumb = make_thumbnail(p, st)
    return YouTubeUpload(
        title=make_title(artist, song, feat, other, lang),
        description=_clean("\n".join(desc)),
        tags=make_tags(artist, song, feat, other, lang),
        language=_LANG[lang],
        audio_language=_LANG[lang],
        playlist="Karaokê" if lang == "pt" else "Karaoke",
        thumbnail=p.rel(thumb) if thumb else None,
        warnings=warnings,
    )


def draft(p: JobPaths, redo: bool = False) -> tuple[YouTubeUpload, bool]:
    """Write output/youtube.json unless it exists (the user may have edited it). With ``redo`` the
    draft is rebuilt but an upload already made (video id, time) is kept. Returns (file, written)."""
    old = read_model_opt(p.youtube, YouTubeUpload)
    if old and not redo:
        return old, False
    if not p.final_video.exists():
        raise ValueError(f"no finished video yet ({p.rel(p.final_video)}): render with the final preset first")
    new = build_draft(p)
    if old:
        new = new.model_copy(update={"video_id": old.video_id, "uploaded_at": old.uploaded_at,
                                     "video_sha1": old.video_sha1})
    write_model(p.youtube, new)
    return new, True


def check(y: YouTubeUpload) -> list[str]:
    """What YouTube would refuse."""
    errors = []
    if not y.title.strip():
        errors.append("the title is empty")
    if len(y.title) > TITLE_MAX:
        errors.append(f"the title is {len(y.title)} characters (at most {TITLE_MAX})")
    if len(y.description.encode()) > DESCRIPTION_MAX:
        errors.append(f"the description is {len(y.description.encode())} bytes (at most {DESCRIPTION_MAX})")
    for field, text in (("title", y.title), ("description", y.description)):
        if "<" in text or ">" in text:
            errors.append(f'the {field} contains "<" or ">", which YouTube refuses')
    if tags_length(y.tags) > TAGS_MAX:
        errors.append(f"the tags add up to {tags_length(y.tags)} characters (at most {TAGS_MAX})")
    return errors


